import openpyxl
import pandas as pd

def obtener_k(ws):
    texto = str(ws["A1"].value)
    return int(texto.split("=")[1].strip())

def leer_numeros(ws):
    numeros = []
    for row in ws.iter_rows(min_row=3, values_only=True):
        for val in row:
            if val is not None and str(val).strip() != "":
                numeros.append(int(val))
    return numeros

def construir_tabla_hash(numeros, k):
    tamano_tabla = len(numeros)
    tabla = [None] * tamano_tabla
    resultados = []
    total_colisiones = 0

    for numero in numeros:
        indice_inicial = numero % k
        indice = indice_inicial % tamano_tabla
        colisiones = 0

        while tabla[indice] is not None:
            colisiones += 1
            indice = (indice_inicial + colisiones) % tamano_tabla

        tabla[indice] = numero
        total_colisiones += colisiones
        resultados.append((numero, indice_inicial, colisiones, indice))

    return tabla, resultados, total_colisiones

wb = openpyxl.load_workbook(filename)

hojas_datos = ["Hoja_1", "Hoja_2", "Hoja_3", "Hoja_4", "Hoja_5"]
resumen = []

for i, nombre_hoja in enumerate(hojas_datos, start=1):
    ws_datos = wb[nombre_hoja]
    k = obtener_k(ws_datos)
    numeros = leer_numeros(ws_datos)
    n = len(numeros)

    tabla, resultados, total_colisiones = construir_tabla_hash(numeros, k)

    nombre_resultado = f"Resultado {i}"
    ws_resultado = wb[nombre_resultado]

    if ws_resultado.max_row > 1:
        ws_resultado.delete_rows(2, ws_resultado.max_row - 1)

    for numero, indice_inicial, colisiones, indice_final in resultados:
        ws_resultado.append([numero, indice_final])

    resumen.append({
        "Hoja": nombre_hoja,
        "k (mod)": k,
        "N° elementos": n,
        "Tamaño tabla ampliada": n,
        "Total colisiones": total_colisiones,
        "Hoja resultado": nombre_resultado,
    })

    print(f"{nombre_hoja} -> {nombre_resultado}: k={k}, elementos={n}, "
          f"tabla ampliada a {n}, colisiones={total_colisiones}")

